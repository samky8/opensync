import 'server-only';
import { createHash, randomBytes } from 'node:crypto';
import { and, eq, lt } from 'drizzle-orm';
import sharp from 'sharp';
import { z } from 'zod';
import { db } from '@/db';
import { socialAccounts, socialPublications, activity } from '@/db/schema';
import { decrypt } from './google';
import { graph, MetaError } from './meta';
import { appUrl } from './server';

export const publishInput = z.object({
  id: z.uuid(),
  accountId: z.uuid(),
  requestId: z.uuid(),
  platform: z.enum(['Instagram', 'Facebook']),
  format: z.enum(['post', 'story']),
  caption: z.string().max(2200),
  image: z
    .string()
    .max(2800000)
    .regex(/^data:image\/jpeg;base64,[A-Za-z0-9+/=]+$/),
});
type Publication = typeof socialPublications.$inferSelect;
export const publicationColumns = {
  id: socialPublications.id,
  accountName: socialPublications.accountName,
  platform: socialPublications.platform,
  format: socialPublications.format,
  status: socialPublications.status,
  remoteId: socialPublications.remoteId,
  error: socialPublications.error,
  createdAt: socialPublications.createdAt,
  updatedAt: socialPublications.updatedAt,
};
export function publicPublication(row: Pick<Publication, keyof typeof publicationColumns>) {
  const stalled =
    ['preparing', 'checking', 'publishing'].includes(row.status) &&
    Date.now() - row.updatedAt.getTime() > 90000;
  return {
    id: row.id,
    accountName: row.accountName,
    platform: row.platform,
    format: row.format,
    status: stalled ? 'unknown' : row.status,
    remoteId: row.remoteId,
    createdAt: row.createdAt,
    error: stalled
      ? 'The request was interrupted. Check the destination account before creating another post.'
      : row.error,
  };
}
export async function createPublication(input: z.infer<typeof publishInput>) {
  const hash = createHash('sha256')
    .update(
      JSON.stringify([
        input.id,
        input.accountId,
        input.platform,
        input.format,
        input.caption,
        input.image,
      ]),
    )
    .digest('hex');
  const [previous] = await db()
    .select()
    .from(socialPublications)
    .where(eq(socialPublications.id, input.requestId));
  if (previous) {
    if (previous.locationId !== input.id || previous.payloadHash !== hash)
      throw new Error('Invalid publication request: this ID already belongs to different content.');
    return publicPublication(previous);
  }
  const [account] = await db()
    .select()
    .from(socialAccounts)
    .where(and(eq(socialAccounts.id, input.accountId), eq(socialAccounts.locationId, input.id)));
  if (!account) throw new Error('Meta account not found. Connect an account first.');
  if (input.platform === 'Instagram' && !account.instagramId)
    throw new Error('Meta requires a linked professional Instagram account.');
  if (
  input.platform === 'Instagram' &&
  input.format === 'story' &&
  account.instagramType === 'CREATOR'
)
    throw new Error(
      'Meta requires an Instagram Business account for story publishing through this connection.',
    );
  const bytes = Buffer.from(input.image.split(',')[1], 'base64');
  if (bytes.length > 2000000) throw new Error('Invalid image: maximum upload is 2 MB.');
  let image: Buffer;
  try {
    const source = sharp(bytes, { limitInputPixels: 1080 * 1920 });
    const metadata = await source.metadata();
    if (
      metadata.format !== 'jpeg' ||
      metadata.width !== 1080 ||
      metadata.height !== (input.format === 'story' ? 1920 : 1080)
    )
      throw new Error();
    image = await source.jpeg({ quality: 92 }).toBuffer();
  } catch {
    throw new Error('Invalid image: use the post or story generated by Social studio.');
  }
  await db()
    .update(socialPublications)
    .set({ image: null })
    .where(lt(socialPublications.mediaExpiresAt, new Date()));
  const [row] = await db()
    .insert(socialPublications)
    .values({
      id: input.requestId,
      locationId: input.id,
      accountId: account.id,
      accountName:
        input.platform === 'Instagram' ? account.instagramName || account.name : account.name,
      platform: input.platform,
      format: input.format,
      caption: input.caption,
      payloadHash: hash,
      image: image.toString('base64'),
      mediaKey: randomBytes(32).toString('hex'),
      mediaExpiresAt: new Date(Date.now() + 86400000),
      status: 'preparing',
    })
    .onConflictDoNothing()
    .returning();
  if (!row) return createPublication(input); // Re-read the unique request after a concurrent insert.
  try {
    const token = decrypt(account.encryptedToken).access_token;
    const imageUrl = `${appUrl()}/api/social/media/${row.mediaKey}`;
    const result =
      input.platform === 'Instagram'
        ? await graph<{ id: string }>(
            `${account.instagramId}/media`,
            token,
            {
              image_url: imageUrl,
              ...(input.format === 'story'
                ? { media_type: 'STORIES' }
                : { caption: input.caption }),
            },
            'POST',
          )
        : await graph<{ id: string }>(
            `${account.pageId}/photos`,
            token,
            { url: imageUrl, published: 'false' },
            'POST',
          );
    if (!result.id) throw new MetaError(0, true);
    const [updated] = await db()
      .update(socialPublications)
      .set({ containerId: result.id, status: 'ready', updatedAt: new Date() })
      .where(eq(socialPublications.id, row.id))
      .returning();
    return publicPublication(updated);
  } catch (error) {
    const [updated] = await db()
      .update(socialPublications)
      .set({
        status: 'failed',
        error:
          error instanceof MetaError
            ? error.message
            : 'Meta media preparation failed. Reconnect or try a new publication.',
        updatedAt: new Date(),
      })
      .where(eq(socialPublications.id, row.id))
      .returning();
    return publicPublication(updated);
  }
}

export async function advancePublication(id: string, locationId: string) {
  const [current] = await db()
    .select()
    .from(socialPublications)
    .where(and(eq(socialPublications.id, id), eq(socialPublications.locationId, locationId)));
  if (!current) throw new Error('Publication not found');
  if (current.status !== 'ready') return publicPublication(current);
  const [account] = await db()
    .select()
    .from(socialAccounts)
    .where(
      and(
        eq(socialAccounts.id, current.accountId || '00000000-0000-4000-8000-000000000000'),
        eq(socialAccounts.locationId, locationId),
      ),
    );
  if (!account) throw new Error('Meta connection not found. Reconnect before continuing.');
  const [claimed] = await db()
    .update(socialPublications)
    .set({ status: 'checking', updatedAt: new Date() })
    .where(and(eq(socialPublications.id, id), eq(socialPublications.status, 'ready')))
    .returning();
  if (!claimed) return publicPublication(current);
  let publishing = false;
  try {
    if (current.mediaExpiresAt < new Date())
      throw new Error('Meta upload expired. Create a new publication.');
    const token = decrypt(account.encryptedToken).access_token;
    if (current.platform === 'Instagram') {
      const result = await graph<{ status_code: string }>(current.containerId!, token, {
        fields: 'status_code',
      });
      if (result.status_code === 'IN_PROGRESS') {
        const [waiting] = await db()
          .update(socialPublications)
          .set({ status: 'ready', updatedAt: new Date() })
          .where(eq(socialPublications.id, id))
          .returning();
        return publicPublication(waiting);
      }
      if (result.status_code !== 'FINISHED')
        throw new Error(
          'Meta could not prepare this image. Create a new publication after checking the account.',
        );
    }
    // Persist BEFORE calling the provider. Crashes/timeouts must never trigger an automatic repeat publish.
    await db()
      .update(socialPublications)
      .set({ status: 'publishing', updatedAt: new Date() })
      .where(eq(socialPublications.id, id));
    publishing = true;
    let remoteId: string | undefined;
    if (current.platform === 'Instagram') {
      const result = await graph<{ id: string }>(
        `${account.instagramId}/media_publish`,
        token,
        { creation_id: current.containerId! },
        'POST',
      );
      remoteId = result.id;
    } else if (current.format === 'story') {
      const result = await graph<{ post_id?: string; success?: boolean }>(
        `${account.pageId}/photo_stories`,
        token,
        { photo_id: current.containerId! },
        'POST',
      );
      remoteId = result.success === false ? undefined : result.post_id;
    } else {
      const result = await graph<{ id: string }>(
        `${account.pageId}/feed`,
        token,
        {
          message: current.caption,
          attached_media: JSON.stringify([{ media_fbid: current.containerId }]),
        },
        'POST',
      );
      remoteId = result.id;
    }
    if (!remoteId) throw new MetaError(0, true);
    const [done] = await db()
      .update(socialPublications)
      .set({ status: 'published', remoteId, error: null, updatedAt: new Date() })
      .where(eq(socialPublications.id, id))
      .returning();
    // Logging cannot turn a confirmed remote publication into a retryable failure.
    await db()
      .insert(activity)
      .values({
        locationId,
        message: `Published ${current.platform} ${current.format} to ${current.accountName}. Provider ID: ${remoteId}`,
      })
      .catch(() => {});
    return publicPublication(done);
  } catch (error) {
    const unknown = publishing && (!(error instanceof MetaError) || error.ambiguous);
    const [failed] = await db()
      .update(socialPublications)
      .set({
        status: unknown ? 'unknown' : 'failed',
        error: unknown
          ? 'Meta did not confirm the outcome. Check your account before posting again; this request will not be retried automatically.'
          : error instanceof MetaError
            ? error.message
            : 'Meta preparation failed or expired. Check your connection and create a new publication.',
        updatedAt: new Date(),
      })
      .where(eq(socialPublications.id, id))
      .returning();
    return publicPublication(failed);
  }
}

export async function boundedJson(req: Request) {
  const reader = req.body?.getReader();
  if (!reader) throw new Error('Invalid request body');
  const chunks: Uint8Array[] = [];
  let length = 0;
  while (true) {
    const { value, done } = await reader.read();
    if (done) break;
    length += value.length;
    if (length > 2900000) {
      await reader.cancel();
      throw new Error('Invalid upload: image is too large.');
    }
    chunks.push(value);
  }
  return JSON.parse(Buffer.concat(chunks).toString('utf8'));
}
